# Welford's algorithm
def runningStats(newValue, currentStats):
    (min, max, count, mean, m2) = currentStats
    if newValue < min: min = newValue
    if newValue > max: max = newValue
    count += 1
    delta = newValue - mean
    mean += delta / count
    delta2 = newValue - mean
    m2 += delta * delta2
    return (min, max, count, mean, m2)


