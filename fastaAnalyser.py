def calculateValueForFeature(sequence, scalesCat):
    sequence = sequence.upper()
    meanPerScale = {}

    for id in SCALE_IDS[scalesCat]:
        avg = avgOverScale(sequence, getDict(id))
        if avg is not None:
            meanPerScale[id] = avg
    
    if not meanPerScale:
        return None
    
    return sum(meanPerScale.values()) / len(meanPerScale)


